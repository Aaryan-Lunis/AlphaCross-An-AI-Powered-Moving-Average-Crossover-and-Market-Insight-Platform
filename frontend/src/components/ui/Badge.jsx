import React from 'react';

const tones = {
  pos: 'bg-pos/10 text-pos',
  neg: 'bg-neg/10 text-neg',
  warn: 'bg-warn/10 text-warn',
  info: 'bg-info/10 text-info',
  accent: 'bg-accent-soft text-accent-hi',
  neutral: 'bg-elevated text-ink-2',
};

const Badge = ({ tone = 'neutral', icon: Icon, children, className = '', title }) => (
  <span
    title={title}
    className={`inline-flex items-center gap-1 rounded-md px-2 py-0.5 text-meta font-medium ${tones[tone]} ${className}`}
  >
    {Icon && <Icon className="h-3 w-3" aria-hidden="true" />}
    {children}
  </span>
);

// Trend/signal badge used in tables and headers.
export const TrendBadge = ({ trend, className = '' }) => {
  const t = (trend || 'neutral').toLowerCase();
  if (t.includes('bull')) return <Badge tone="pos" className={className}>Bullish</Badge>;
  if (t.includes('bear')) return <Badge tone="neg" className={className}>Bearish</Badge>;
  return <Badge tone="neutral" className={className}>Neutral</Badge>;
};

// Marks content produced by a language model, as opposed to market data.
export const AiBadge = ({ className = '' }) => (
  <Badge tone="accent" className={className} title="Generated by an AI model, not a market data feed">
    AI-generated
  </Badge>
);

export default Badge;
